import { test, expect } from './fixtures.js';
test('responsive catalog and Bangla navigation', async ({page},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Everyday, beautifully dressed.'})).toBeVisible();
  await expect(page.locator('.hero-image img')).toHaveJSProperty('naturalWidth',1000);
  await expect(page.locator('.product-card')).toHaveCount(10);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.screenshot({path:testInfo.outputPath('home.png'),fullPage:true});
  await page.getByRole('button',{name:'বাংলা',exact:true}).click();
  await expect(page.locator('html')).toHaveAttribute('lang','bn');
  await expect(page.getByRole('heading',{name:'প্রতিদিন, নতুন সাজে।'})).toBeVisible();
  await page.goto('/shop?q=linen&sort=price_asc');
  await expect(page.locator('.product-card')).toHaveCount(1);
  await expect(page.locator('.price')).toContainText('৳2,190');
  expect(errors).toEqual([]);
});
test('guest purchase, invoice and cancellation work end to end', async ({page},testInfo)=>{
  await page.goto('/products/linen-relaxed-shirt');
  await page.getByRole('combobox',{name:'Color',exact:true}).selectOption('Sky blue');
  await page.getByRole('combobox',{name:'Size',exact:true}).selectOption('M');
  await page.getByRole('button',{name:'Add to bag',exact:true}).click();
  await expect(page.getByText('Added to your bag.',{exact:false})).toBeVisible();
  await page.getByRole('link',{name:'View bag',exact:true}).click();
  await expect(page.locator('.bag-item')).toHaveCount(1);
  await page.getByRole('link',{name:'Continue to checkout'}).click();
  await page.getByLabel('Full name',{exact:true}).fill('Browser test buyer');
  await page.getByLabel('Email',{exact:true}).fill('browser@example.test');
  await page.getByLabel('Phone',{exact:true}).fill('01712345678');
  await page.getByLabel('Street address').fill('12 Development Road');
  await page.getByLabel('District',{exact:true}).fill('Dhaka');
  await page.getByRole('combobox',{name:'Shipping method',exact:true}).selectOption({label:'Dhaka delivery · ৳80 (Dhaka)'});
  await page.locator('input[name=terms]').check();
  await page.getByRole('button',{name:'Review your order',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Review your order',exact:true})).toBeVisible();
  await expect(page.locator('dl .total')).toContainText('৳2,270');
  await page.getByRole('button',{name:'Place order · Cash on delivery',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Order received'})).toBeVisible();
  await expect(page.locator('.status-grid')).toContainText('Pending');
  await page.screenshot({path:testInfo.outputPath('receipt.png'),fullPage:true});
  const invoice=await page.getByRole('link',{name:'Printable invoice'}).getAttribute('href');
  const receipt=page.url();
  await page.goto(invoice);
  await expect(page.getByRole('heading',{name:/Invoice #/})).toBeVisible();
  await page.goto(receipt);
  await page.getByRole('button',{name:'Cancel order',exact:true}).click();
  await expect(page.locator('.status-grid')).toContainText('Cancelled');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
});
